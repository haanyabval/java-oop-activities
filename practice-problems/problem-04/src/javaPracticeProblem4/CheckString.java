// Practice Problem 4 - Problem 9: Write a program to check if a given string equals "Java".
package javaPracticeProblem4;

public class CheckString {
    public static void main(String[] args) {
        String word = "Jav";
        System.out.println("GIVEN WORD: Jav");
        if (word.equals("Java"))
            System.out.println("The string equals 'Java'.");
        else
            System.out.println("The string does not equal 'Java'.");
    }
}
