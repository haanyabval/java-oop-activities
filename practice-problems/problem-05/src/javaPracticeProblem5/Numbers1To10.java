// Practice Problem 5 - Problem 1: Write a program to print numbers from 1 to 10.
package javaPracticeProblem5;

public class Numbers1To10 {
    public static void main(String[] args) {
        System.out.println("OUTPUT:");
        for (int i = 1; i <= 10; i++) {
            System.out.println(i);
        }
    }
}
