// Practice Problem 1 - Problem 4: Write a program to print the product of three numbers.
public class Productof3 {
    public static void main(String[] args) {

        //Declaration
        int num1 = 12, num2 = 32, num3 = 21, product = 0;

        //Process
        product = num1 * num2 * num3;

        //Output
        System.out.print("The product of three numbers is equal to " + product + ".");
    }
}
