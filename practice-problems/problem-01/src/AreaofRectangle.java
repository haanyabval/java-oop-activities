// Practice Problem 1 - Problem 8: Write a program to print the area of a rectangle (length x width).
public class AreaofRectangle {
    public static void main(String[] args) {

        // Declaration
        int length = 3, width = 6, area = 0;

        //Process
        area = length * width;

        //Output
        System.out.println("The area of a rectangle is equal to " + area + ".");

    }
}
